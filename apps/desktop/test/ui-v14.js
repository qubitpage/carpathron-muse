// Screenshots of the 1.4 UI: capabilities bar, effort, Full mode, server picker, server editor, tools settings, image in chat.
process.env.NODE_TLS_REJECT_UNAUTHORIZED = '0';
const fs = require('fs'), os = require('os'), path = require('path');
const fake = require('./fake-meta');
const fakeSsh = require('./fake-ssh');
const { startServer } = require('../backend/server');
const { chromium } = require(process.env.PW || 'playwright');
(async () => {
  const out = process.argv[2];
  await fake.start(18721); await fakeSsh.start(18723, { home: fs.mkdtempSync(path.join(os.tmpdir(), 'mc-ui14home-')) });
  const dataDir = fs.mkdtempSync(path.join(os.tmpdir(), 'mc-ui14-'));
  const ws = fs.mkdtempSync(path.join(os.tmpdir(), 'mc-ui14ws-'));
  fs.writeFileSync(path.join(dataDir, 'settings.json'), JSON.stringify({ apiKey: 'test-key', apiBase: 'http://127.0.0.1:18721/v1', engine: 'api', workspace: ws, port: 18722 }));
  const srv = await startServer({ dataDir, log: () => {} });
  srv.remote.save({ name: 'my-vps', host: '127.0.0.1', port: 18723, username: 'tester', password: 'secret', defaultPath: os.tmpdir() });
  const b = await chromium.launch({ args: ['--ignore-certificate-errors'] });
  const p = await b.newPage({ viewport: { width: 1360, height: 860 } });
  const errs = []; p.on('pageerror', (e) => errs.push(e.message)); p.on('console', (m) => m.type() === 'error' && errs.push(m.text()));
  await p.goto(`https://localhost:18722/?t=${srv.token}`);
  await p.waitForTimeout(1000);
  await p.screenshot({ path: `${out}/a-empty.png` });
  await p.click('#segMode button[data-mode="full"]');
  await p.fill('#input', 'draw a logo'); await p.keyboard.press('Enter');
  await p.waitForTimeout(1500);
  await p.screenshot({ path: `${out}/b-image.png` });
  await p.click('#chipWhere'); await p.waitForTimeout(300);
  await p.click('.modal .opt:nth-of-type(2)'); await p.waitForTimeout(1500);
  await p.screenshot({ path: `${out}/c-where.png` });
  await p.click('text=Use this server'); await p.waitForTimeout(500);
  await p.fill('#input', 'remote run something'); await p.keyboard.press('Enter');
  await p.waitForTimeout(2500);
  await p.click('details.fold.tool:last-of-type summary').catch(() => {});
  await p.screenshot({ path: `${out}/d-remote-chat.png` });
  await p.selectOption('#selModel', 'sam-3.1'); await p.waitForTimeout(500);
  await p.screenshot({ path: `${out}/e-sam-caps.png`, clip: { x: 272, y: 0, width: 1088, height: 140 } });
  await p.click('#nav button[data-view="settings"]'); await p.waitForTimeout(1200);
  await p.evaluate(() => document.querySelector('#srvCard').scrollIntoView());
  await p.waitForTimeout(300);
  await p.screenshot({ path: `${out}/f-settings.png` });
  await p.click('.modal .btn:last-child').catch(() => {});
  await p.click('#nav button[data-view="remote"]'); await p.waitForTimeout(1200);
  await p.click('#btnGenKey'); await p.waitForTimeout(300); await p.click('.modal .btn.primary'); await p.waitForTimeout(800);
  await p.click('text=⌨ Terminal'); await p.waitForTimeout(2500);
  await p.fill('#termIn', 'echo hello-terminal'); await p.keyboard.press('Enter'); await p.waitForTimeout(2500);
  await p.screenshot({ path: `${out}/h-remote.png`, fullPage: true });
  await p.click('#nav button[data-view="plugins"]'); await p.waitForTimeout(1000);
  await p.screenshot({ path: `${out}/i-plugins.png` });
  await p.click('#nav button[data-view="projects"]'); await p.waitForTimeout(500);
  await p.click('#btnNewProject'); await p.waitForTimeout(300);
  await p.fill('.modal .dlg-input', 'EU funding'); await p.keyboard.press('Enter'); await p.waitForTimeout(800);
  await p.screenshot({ path: `${out}/j-project.png` });
  console.log('errors:', JSON.stringify(errs));
  await b.close(); await srv.close(); process.exit(0);
})().catch((e) => { console.error(e); process.exit(1); });
