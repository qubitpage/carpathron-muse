// Screenshots + checks of Robot → Car settings and Health on the practice car.
process.env.NODE_TLS_REJECT_UNAUTHORIZED = '0';
const fs = require('fs'), os = require('os'), path = require('path');
const { startServer } = require('../backend/server');
const { chromium } = require(process.env.PW || 'playwright');
(async () => {
  const out = process.argv[2] || fs.mkdtempSync(path.join(os.tmpdir(), 'ui-carlab-'));
  const dataDir = fs.mkdtempSync(path.join(os.tmpdir(), 'mc-uicl-'));
  const ws = fs.mkdtempSync(path.join(os.tmpdir(), 'mc-uiclws-'));
  fs.writeFileSync(path.join(dataDir, 'settings.json'), JSON.stringify({ apiKey: 'x', apiBase: 'http://127.0.0.1:1/v1', engine: 'api', workspace: ws, port: 18742 }));
  const srv = await startServer({ dataDir, log: () => {} });
  const b = await chromium.launch({ args: ['--ignore-certificate-errors'] });
  const p = await b.newPage({ viewport: { width: 1280, height: 860 } });
  const errs = []; p.on('pageerror', (e) => errs.push(e.message)); p.on('console', (m) => m.type() === 'error' && errs.push(m.text()));
  await p.goto(`https://localhost:18742/?t=${srv.token}`);
  await p.waitForTimeout(800);
  await p.evaluate(() => window.MCui.openRobot('carset'));
  await p.waitForTimeout(800);
  await p.screenshot({ path: `${out}/1-no-car.png` });
  await p.click('text=Use the practice car');
  await p.waitForSelector('.setting');
  await p.waitForTimeout(400);
  await p.screenshot({ path: `${out}/2-motors.png`, fullPage: true });
  await p.locator('.board-card').screenshot({ path: `${out}/2b-board.png` });
  // a pin used twice is refused before saving
  await p.locator('.setting', { hasText: 'Right wheels: speed pin' }).locator('select').selectOption('13');
  await p.waitForTimeout(500);
  const err = await p.locator('.setting.error').count();
  const disabled = await p.locator('.carset-bar .btn.primary').isDisabled();
  await p.screenshot({ path: `${out}/3-clash.png`, fullPage: true });
  await p.click('text=Undo changes');
  await p.click('.carset-nav button:has-text("Driving")');
  await p.locator('.setting', { hasText: 'Stop distance' }).locator('input.num').fill('250');
  await p.waitForTimeout(400);
  await p.click('.carset-bar .btn.primary');
  await p.waitForTimeout(800);
  const saved = await p.evaluate(async (t) => (await (await fetch('/api/robot/car/settings', { headers: { 'x-mc-token': t } })).json()).values.stopMm, srv.token);
  await p.evaluate(() => window.MCui.openRobot('health'));
  await p.waitForTimeout(500);
  await p.selectOption('#robotHealth .practice-strip select', 'invertLeft');
  await p.waitForTimeout(300);
  await p.click('text=Check + test the wheels');
  await p.waitForSelector('.health-sum', { timeout: 20000 });
  await p.waitForTimeout(300);
  await p.screenshot({ path: `${out}/4-health.png`, fullPage: true });
  const fixBtns = await p.locator('text=Apply this fix').count();
  await p.click('text=Apply this fix');
  await p.waitForTimeout(800);
  await p.click('text=Check + test the wheels');
  await p.waitForTimeout(4500);
  const after = await p.locator('.health-item.warn, .health-item.bad').count();
  await p.screenshot({ path: `${out}/5-fixed.png`, fullPage: true });
  await p.locator('.cal-step').nth(0).locator('button', { hasText: 'Start' }).click();
  await p.waitForFunction(() => /✓|⚠|✕/.test(document.querySelector('.cal-step .cal-res').textContent), null, { timeout: 15000 });
  const calText = await p.locator('.cal-step .cal-res').first().textContent();
  await p.locator('.cal-card').screenshot({ path: `${out}/6-calibration.png` });
  // Board & parts
  await p.evaluate(() => window.MCui.openRobot('parts'));
  await p.waitForSelector('#robotParts .board-svg');
  await p.waitForTimeout(800);
  await p.locator('#robotParts .board-svg g.pin[data-gpio="13"]').dispatchEvent('click');
  await p.click('text=🔍 Read');
  await p.waitForTimeout(600);
  const pinRead = await p.locator('#robotParts .pin-info').textContent();
  await p.screenshot({ path: `${out}/7-parts-cam.png`, fullPage: true });
  await p.selectOption('#robotParts .parts-top select', 'esp32devkit');
  await p.waitForTimeout(600);
  await p.click('text=＋ Add a part');
  await p.click('.part-btn:has-text("SG90 servo")');
  await p.waitForTimeout(500);
  await p.click('text=✓ Add to my robot');
  await p.waitForTimeout(600);
  await p.click('text=＋ Add a part');
  await p.click('.part-btn:has-text("VL53L0X")');
  await p.waitForTimeout(500);
  await p.click('text=✓ Add to my robot');
  await p.waitForTimeout(600);
  const wires = await p.locator('#robotParts .schem-svg .wire').count();
  await p.click('text=📋 Starter code');
  await p.waitForTimeout(400);
  const code = await p.locator('#robotParts pre').first().textContent();
  await p.screenshot({ path: `${out}/8-parts-devkit.png`, fullPage: true });
  await p.locator('#robotParts .parts-grid > div').nth(1).screenshot({ path: `${out}/8b-schematic.png` });
  await p.selectOption('#robotParts .parts-top select', 'mega2560');
  await p.waitForTimeout(600);
  await p.locator('#robotParts .board-card').screenshot({ path: `${out}/9-mega.png` });
  await p.selectOption('#robotParts .parts-top select', 'uno');
  await p.waitForTimeout(600);
  await p.locator('#robotParts .board-card').screenshot({ path: `${out}/9b-uno.png` });
  const partsOk = /used by the motors/.test(pinRead) && wires >= 6 && /SERVO|SG90/.test(code) && /Wire.begin\(/.test(code);
  console.log(JSON.stringify({ pinRead: pinRead.slice(0, 160), wires, partsOk }));
  console.log(JSON.stringify({ out, errs, err, disabled, saved, fixBtns, problemsAfterFix: after, calText }));
  await b.close(); await srv.close(); process.exit(errs.length || !err || !disabled || saved !== 250 || !fixBtns || after || !/✓/.test(calText) || !partsOk ? 1 : 0);
})().catch((e) => { console.error(e); process.exit(1); });
